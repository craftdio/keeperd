export function airflowDockerArguments({ profile, container, database }) {
    return [
        'run',
        '--rm',
        '--network',
        `container:${container}`,
        '--memory=1g',
        '--cpus=1',
        '--pids-limit=256',
        '--read-only',
        '--tmpfs',
        '/opt/airflow:rw,noexec,nosuid,size=128m',
        '-e',
        'AIRFLOW_HOME=/opt/airflow',
        '-e',
        'AIRFLOW__CORE__DAGS_FOLDER=/opt/airflow/empty-dags',
        '-e',
        'AIRFLOW__CORE__PLUGINS_FOLDER=/opt/airflow/empty-plugins',
        '-e',
        'AIRFLOW__CORE__LOAD_EXAMPLES=False',
        '-e',
        'AIRFLOW__CORE__EXECUTOR=SequentialExecutor',
        '-e',
        `AIRFLOW__CORE__AUTH_MANAGER=${profile.authManager}`,
        '-e',
        `AIRFLOW__DATABASE__SQL_ALCHEMY_CONN=postgresql+psycopg2://postgres@localhost:5432/${database}`,
        '--entrypoint',
        'airflow',
        profile.airflowImage,
        'db',
        'migrate',
    ];
}
